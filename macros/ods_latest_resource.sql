{# 同じ（自治体・調査年月日・地域）の行が複数のリソースから入ったとき、現行の版だけを残す。

   月次で公開する自治体には、前の年の同月のファイルを新しい月のデータで上書きしつつ、
   正しい名前の新しいリソースも登録する例がある（練馬区の地域・年齢別人口では
   131202_population_202503.csv が 2026-03-01 のデータを返し、
   131202_population_202603.csv と中身が一致する）。カタログ側の URL は別なので
   取り込みは両方を取り、同じ月の地域が二重に入る。

   採るのはリソースの最終更新時点が新しい側。原典が「どちらが現行か」を述べている唯一の
   手がかりであり、名前の付け替えや複数月をまとめたファイルの登録でも同じ向きに働く。
   最終更新時点が同じ（または両方とも登録が無い）ときはリソース ID で決める。値の優劣は
   付けられないが、リソースが違えばビルドのたびに採用する行が入れ替わらない。

   自治体の識別には org_code（パッケージの所属組織）を使う。CSV 側の地方公共団体名は
   列を持たない自治体があり NULL になる。

   適用するのは、キーの列が正規化後の値だけに束縛される位置（正規化した CTE の外側）。
   qualify から元の列が見えると、DuckDB は FROM 側を優先するため、同名のエイリアスで
   正規化していても比較は正規化前の値で行われる。

   最終更新時点もリソース ID も並ぶのは、1つのファイルの中に同じキーの行が2度ある場合で、
   このときどちらが残るかは決まらない。原典の側の欠陥であり、値が違えば取り違える。 #}

{% macro ods_latest_resource(partition_by) -%}
qualify row_number() over (
    partition by {{ partition_by | join(', ') }}
    order by resource_modified desc nulls last, resource_id
) = 1
{%- endmacro %}
